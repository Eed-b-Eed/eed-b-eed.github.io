function showForms() {

const selectedVerbs =
trainerData.verbs.filter(verb =>
Array.from(
document.querySelectorAll(".verb-btn.active")
).some(btn => btn.textContent === verb.label)
);

const selectedForms =
Array.from(
document.querySelectorAll(
"#formCheckboxes .form-btn.active"
)
).map(btn => btn.textContent);

const showClassical =
document.getElementById("showClassical").checked;

const showKhalili =
document.getElementById("showKhalili").checked;

const hideHarakat =
document.getElementById("hideHarakat").checked;

const hideStretch =
document.getElementById("hideStretch").checked;

const plainKhalili =
document.getElementById("plainKhalili").checked;

if (!showClassical && !showKhalili) {

results.innerHTML =
            "<p>Please select at least one type of Arabic.</p>";

return;
}

if (selectedVerbs.length === 0) {

results.innerHTML =
            "<p>Please select at least one action.</p>";

return;
}

if (selectedForms.length === 0) {

results.innerHTML =
            "<p>Please select at least one person.</p>";

return;
}

let html = '<table class="result-table">';

if (showClassical && showKhalili) {

html +=
'<tr>' +
'<th></th>' +
'<th>الخليلي</th>' +
'<th>الفصحى</th>' +
'</tr>';

selectedVerbs.forEach(verb => {

html +=
'<tr>' +
'<th colspan="3" class="verb-heading">' +
verb.label +
'</th>' +
'</tr>';


selectedForms.forEach(form => {

const index =
trainerData.forms.indexOf(form);

let classicalForm =
verb.varieties.Classical[index];

if (hideHarakat) {
classicalForm =
removeHarakat(classicalForm);
}

let khaliliForm =
latinToArabic(
verb.varieties.Khalili[index],
hideStretch,
plainKhalili
);

html +=
'<tr>' +
'<td>' + form + '</td>' +
'<td class="arabic">' +
khaliliForm +
'</td>' +
'<td class="arabic">' +
classicalForm +
'</td>' +
'</tr>';

});

});

} else {

html +=
'<tr>' +
'<th></th>' +
'<th>' +
(showClassical ? 'الفصحى' : 'الخليلي') +
'</th>' +
'</tr>';

selectedVerbs.forEach(verb => {

html +=
'<tr>' +
'<th colspan="2" class="verb-heading">' +
verb.label +
'</th>' + 
'</tr>';

selectedForms.forEach(form => {

const index =
trainerData.forms.indexOf(form);

let displayForm;

if (showClassical) {

displayForm =
verb.varieties.Classical[index];

if (hideHarakat) {
displayForm =
removeHarakat(displayForm);
}

} else {

displayForm =
latinToArabic(
verb.varieties.Khalili[index],
hideStretch,
plainKhalili
);

}

html +=
'<tr>' +
'<td>' + form + '</td>' +
'<td class="arabic">' +
displayForm +
'</td>' +
'</tr>';

});

});

}

html += "</table>";

results.innerHTML = html;

}

function removeHarakat(text) {

return text.replace(
/[\u064B-\u065F\u0670]/g,
""
);

}

function latinToArabic(text, hideStretch = false, plainKhalili = false) {

if (plainKhalili) {

text = text
.replace(/[auei]/g, '')
.replace(/U/g, 'w')
.replace(/O/g, 'w')
.replace(/A/g, '1')
.replace(/I/g, 'y');

}

const stretch = hideStretch ? '' : 'ــ';

const map = {
'1':'ا',
'b':'ب',
't':'ت',
'j':'ج',
'7':'ح',
'x':'خ',
'd':'د',
'r':'ر',
'z':'ز',
's':'س',
'$':'ش',
'9':'ص',
'6':'ط',
'3':'ع',
'G':'غ',
'f':'ف',
'q':'ق',
'k':'ك',
'l':'ل',
'm':'م',
'n':'ن',
'h':'ه',
'w':'و',
'y':'ي',

'a':'<span style="color:limegreen;">' + stretch + 'َ' + stretch + '</span>',
'A':'<span style="color:limegreen;">' + stretch + 'َ' + stretch + 'ا</span>',
'u':'<span style="color:orange;">' + stretch + 'ُ' + stretch + '</span>',
'U':'<span style="color:orange;">' + stretch + 'ُ' + stretch + 'و</span>',
'O':'<span style="color:#FFD8A8;">' + stretch + 'ُ' + stretch + 'و</span>',
'i':'<span style="color:darkviolet;">' + stretch + 'ِ' + stretch + '</span>',
'I':'<span style="color:darkviolet;">' + stretch + 'ِ' + stretch + 'ي</span>',
'e':'<span style="color:skyblue;">' + stretch + 'ِ' + stretch + '</span>',
'~':'<span style="color:darkviolet;">ّ</span>',
};

let bold = false;
let output = '';

for (const char of text) {

if (char === '|') {
output += bold
? '</span>'
: '<span style="border-bottom:1px dotted #b0b0b0;">';
bold = !bold;
continue;
}

output += map[char] || char;
}

return output;
}

